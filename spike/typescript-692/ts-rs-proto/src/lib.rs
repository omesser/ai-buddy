//! Spike 692: the payload shapes that cross from Rust to the webview, copied
//! from src-tauri/src/main.rs and acp_wire.rs, with `ts_rs::TS` derived only
//! under `cfg(test)`. The shipped binary would carry no ts-rs code.
#![allow(dead_code)]
use std::collections::BTreeMap;

#[cfg(test)]
use ts_rs::TS;

#[derive(Clone, Copy, serde::Serialize)]
#[cfg_attr(test, derive(TS), ts(export))]
pub enum Primitive { Idle, Walk, Land, Sit, Sleep, React, Talk, Hold, Chase, Jump }

#[derive(Clone, Copy, serde::Serialize)]
#[cfg_attr(test, derive(TS), ts(export))]
pub enum State { Grounded, Falling, Dragged, Perched, Climbing, Asleep }

#[derive(serde::Serialize)]
